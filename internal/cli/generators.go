// sedum:setFunction {"v":2,"tier":"owned","record":"prov-2026-3e5a05dc","gen":"sha256:601088eb1aa16c655a8a3610e01f220fcceaa8b83b311c76b4ac9a810345d516","pkg":"sha256:6589611adfb6618a7920e43f951a79901428192ea95c1084fde9f222aecd9537","id":{"file":"internal/cli/generators.go","name":"planInstall"},"kwargs":"sha256:7b51579c9a7e3ca7391703d6d518e41c74b77861e04f979fb96310aad46ece69","body":"sha256:7c7ee6411c9f362b028fa566bb65c78a85d3af1b1ba490577a43ef20d799524d"}
func planInstall(names []string, opts installOptions) ([]installEntry, error) {
	var entries []installEntry
	for _, name := range names {
		if name == "" || name == "." || name == ".." || strings.ContainsAny(name, "/\\") || strings.ContainsRune(name, 0) {
			return nil, fmt.Errorf("invalid package name %q", name)
		}
		files, err := loadPackageFiles(name, opts)
		if err != nil {
			return nil, err
		}
		rels := make([]string, 0, len(files))
		for rel := range files {
			rels = append(rels, rel)
		}
		sort.Strings(rels)
		for _, rel := range rels {
			if !filepath.IsLocal(rel) {
				return nil, fmt.Errorf("package %q: refusing file path %q", name, rel)
			}
			path := filepath.Join(opts.Dir, name, rel)
			status := "create"
			existing, err := os.ReadFile(path)
			switch {
			case err == nil && bytes.Equal(existing, files[rel]):
				status = "identical"
			case err == nil:
				status = "differs"
			case !os.IsNotExist(err):
				return nil, err
			}
			entries = append(entries, installEntry{Path: path, Status: status, Data: files[rel]})
		}
	}
	return entries, nil
}


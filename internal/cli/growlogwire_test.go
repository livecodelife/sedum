func TestWriteGrowLog(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "grow.jsonl")
	t.Setenv("SEDUM_GROW_LOG", path)
	t.Setenv("SEDUM_GROW_LOG_SKIPS", "")
	lines := func() int {
		data, err := os.ReadFile(path)
		if err != nil {
			return 0
		}
		return strings.Count(string(data), "\n")
	}
	var errOut bytes.Buffer
	base := GrowConfig{Model: "m"}
	writeGrowLog(&errOut, base, growLogResult(), nil, time.Now())
	if lines() != 1 {
		t.Fatalf("a normal grow wrote %d lines, want 1", lines())
	}
	for name, cfg := range map[string]GrowConfig{
		"dry run":    {Model: "m", DryRun: true},
		"check":      {Model: "m", Check: true},
		"stamp":      {Model: "m", Stamp: true},
		"stop after": {Model: "m", StopAfter: "files"},
	} {
		writeGrowLog(&errOut, cfg, growLogResult(), nil, time.Now())
		if lines() != 1 {
			t.Fatalf("%s must not append, file has %d lines", name, lines())
		}
	}
	writeGrowLog(&errOut, base, nil, errors.New("boom"), time.Now())
	if lines() != 2 {
		t.Fatalf("a failed grow wrote %d lines, want 2", lines())
	}
	t.Setenv("SEDUM_GROW_LOG", "off")
	writeGrowLog(&errOut, base, growLogResult(), nil, time.Now())
	if lines() != 2 || errOut.Len() != 0 {
		t.Fatalf("off must append nothing: %d lines, warning %q", lines(), errOut.String())
	}
	blocked := filepath.Join(dir, "file")
	if err := os.WriteFile(blocked, nil, 0o644); err != nil {
		t.Fatal(err)
	}
	t.Setenv("SEDUM_GROW_LOG", filepath.Join(blocked, "x", "grow.jsonl"))
	writeGrowLog(&errOut, base, growLogResult(), nil, time.Now())
	if !strings.HasPrefix(errOut.String(), "warning: ") {
		t.Fatalf("an unwritable log must warn, got %q", errOut.String())
	}
}


func (c *Cell) add(s Sample) {
	c.Samples++
	if s.Compiled {
		c.Compiled++
	}
	if s.Passed {
		c.Passed++
	}
	c.Calls += s.Calls
	c.Rejected += s.Rejected
	c.Repairs += s.Repairs
	c.PromptTokens += s.PromptTokens
	c.CompletionTokens += s.CompletionTokens
}

